def render_block(values: dict[str, list[str]]) -> str:
    lines = ["applies_to:"]
    for key in ("系统", "条件", "不适用"):
        quoted = ", ".join(f'"{item}"' for item in values[key])
        lines.append(f"  {key}: [{quoted}]")
    return "\n".join(lines) + "\n"


def render_authority_contract(values: dict[str, list[str]]) -> str:
    systems = "；".join(values["系统"])
    conditions = "；".join(values["条件"])
    excluded = "；".join(values["不适用"])
    return (
        "## 权威问答口径\n\n"
        f"- 本页可承担的回答范围：{systems}；成立条件：{conditions}。\n"
        f"- 遇到以下情况必须拒绝确定结论或转入专项页/实测：{excluded}。\n"
        "- 具体数值、兼容性、软件行为或安全结论只使用正文就近绑定的来源，"
        "并同时受 `stale_after` 与人工 `verified.scope` 限制。\n\n"
    )


